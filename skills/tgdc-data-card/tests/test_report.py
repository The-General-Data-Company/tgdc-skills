"""Synthetic-only PDF contract and adverse-input checks."""
import copy
import hashlib
import json
import re
from pathlib import Path
import subprocess
import sys
import tempfile
import unittest
from unittest.mock import patch

from pypdf import PdfReader

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / 'scripts'))
from report import render
from profiler import profile


class ReportTests(unittest.TestCase):
    def setUp(self):
        self.temp = tempfile.TemporaryDirectory()
        self.addCleanup(self.temp.cleanup)
        self.folder = Path(self.temp.name).resolve()
        self.profile = json.loads((ROOT / 'assets/examples/profile.synthetic.json').read_text())
        self.answers = json.loads((ROOT / 'assets/examples/answers.synthetic.json').read_text())
        self.out = self.folder / 'card.pdf'

    def build(self):
        p, a = self.folder / 'profile.json', self.folder / 'answers.json'
        p.write_text(json.dumps(self.profile))
        a.write_text(json.dumps(self.answers))
        render(p, a, self.out)
        reader = PdfReader(self.out)
        return reader, '\n'.join(page.extract_text() for page in reader.pages)

    def test_fixture_a4_identity_counts_and_evidence(self):
        reader, text = self.build()
        self.assertTrue(3 <= len(reader.pages) <= 5)
        for page in reader.pages:
            self.assertAlmostEqual(float(page.mediabox.width), 595.2756, places=2)
            self.assertAlmostEqual(float(page.mediabox.height), 841.8898, places=2)
        first = reader.pages[0].extract_text()
        self.assertIn('16', first)
        self.assertIn('11 of 15', first)
        self.assertIn('Files with extracted text', first)
        self.assertIn('Inferred / examined sample', first)
        self.assertIn('UNKNOWN', first)
        for value in ['TGDC', 'levin@thegeneraldata.com', 'Measured', 'Provider-declared', 'Inferred', '15 attempted sampled files', '4 of 15', '10 unknown', self.profile['generated_at']]:
            self.assertIn(value, text)
        self.assertEqual(reader.metadata.author, 'TGDC')
        self.assertNotIn('lower bound', text.lower())
        self.assertNotIn('total archive rows', text.lower())

    def test_private_keys_and_paths_never_autogenerated(self):
        self.profile['sources'] = ['/private/customer/source.txt']
        self.profile['manifest'] = {'path': '/private/customer/secret.docx'}
        _, text = self.build()
        self.assertNotIn('/private/customer', text)
        self.assertNotIn('secret.docx', text)
        self.assertNotIn('profile.synthetic.json', text)

    def test_long_narrative_and_long_url_paginate_without_loss(self):
        self.answers['notes'] = 'START ' + ('Long synthetic provider narrative. ' * 310) + ' END'
        self.answers['custom_context'] = 'https://example.com/' + 'abcdefgh' * 140 + '?x=1&y=2'
        reader, text = self.build()
        self.assertGreater(len(reader.pages), 5)
        self.assertIn('START', text)
        self.assertIn('END', text)
        body = re.sub(r'DATA CARD / FOR REVIEW\nTGDC / \d+\nlevin@thegeneraldata.com\n', '', text)
        compact = ''.join(body.split())
        self.assertIn(''.join(self.answers['notes'].split()), compact)
        self.assertIn(''.join(self.answers['custom_context'].split()), compact)

    def test_long_overview_fields_still_make_one_complete_overview(self):
        for key in ['dataset_name', 'business', 'archive_description', 'period', 'notes', 'anonymization']:
            self.answers[key] = ('Long synthetic declaration ' * 20) + ' END'
        reader, _ = self.build()
        first = reader.pages[0].extract_text()
        self.assertIn('ANONYMIZATION', first)
        self.assertIn('Review this report', first)
        self.assertIn('Formats & coverage', reader.pages[1].extract_text())

    def test_markup_controls_accents_are_plain_safe_text(self):
        self.answers['dataset_name'] = 'Synthetic: Grüße Łódź'
        self.answers['notes'] = '<b>literal</b> & <img src="/secret">\x01'
        _, text = self.build()
        for value in ['Grüße Łódź', '<b>literal</b>', '<img src="/secret">', '[U+0001]']:
            self.assertIn(value, text)

    def test_unsupported_provider_scripts_preserve_prior_output(self):
        for value in ['中文声明', 'بيانات المؤسسة']:
            with self.subTest(value=value):
                self.answers['notes'] = value
                self.out.write_bytes(b'PRIOR OUTPUT')
                with self.assertRaisesRegex(ValueError, 'English or Latin-script'):
                    self.build()
                self.assertEqual(self.out.read_bytes(), b'PRIOR OUTPUT')

    def test_missing_answers_stay_questions(self):
        _, text = self.build()
        self.assertIn('How should records', text)
        self.assertIn('Which stages', text)
        self.assertNotIn('What rights and permissions', text)

    def test_empty_profile_is_useful_and_unknown_is_not_zero(self):
        source = self.folder / 'empty-source'
        source.mkdir()
        self.profile = profile([source], self.folder / 'empty-report')
        self.assertEqual(self.profile['extraction']['attempted'], 0)
        self.assertIsNone(self.profile['metrics']['files_with_extracted_text']['value'])
        self.answers = {}
        reader, text = self.build()
        self.assertIn('Not examined', reader.pages[0].extract_text())
        self.assertIn('No files were inventoried', text)
        self.assertIn('Not available', text)
        self.assertNotIn('0.0% English', text)

    def test_unsupported_only_cli_profile_renders_without_claiming_examined_text(self):
        source, output = self.folder / 'dwg-source', self.folder / 'dwg-report'
        source.mkdir()
        original = b'Synthetic unsupported DWG fixture only.'
        selected = source / 'synthetic.dwg'
        selected.write_bytes(original)
        cli = str(ROOT / 'scripts/datacard.py')
        scanned = subprocess.run([sys.executable, cli, 'profile', '--source', str(source), '--output', str(output)], capture_output=True, text=True)
        self.assertEqual(scanned.returncode, 0, scanned.stderr)
        self.profile = json.loads((output / 'profile.json').read_text())
        self.assertEqual(self.profile['inventory']['files'], 1)
        self.assertEqual(self.profile['extraction']['attempted'], 0)
        self.assertIsNone(self.profile['metrics']['files_with_extracted_text']['value'])
        answers = output / 'answers.json'
        answers.write_text('{}')
        rendered = subprocess.run([sys.executable, cli, 'render', '--profile', str(output / 'profile.json'), '--answers', str(answers), '--output', str(self.out)], capture_output=True, text=True)
        self.assertEqual(rendered.returncode, 0, rendered.stderr)
        first = PdfReader(self.out).pages[0].extract_text()
        self.assertIn('Not examined', first)
        self.assertIn('DWG', first)
        self.assertNotIn('0 of 0', first)
        self.assertEqual(selected.read_bytes(), original)

    def test_capped_inventory_and_sample_scope_visible_on_first_page(self):
        self.profile['scope']['enumeration_complete'] = False
        for metric in self.profile['metrics'].values():
            metric['coverage']['enumeration_complete'] = False
        reader, _ = self.build()
        self.assertIn('INCOMPLETE INVENTORY', reader.pages[0].extract_text())
        self.assertIn('11 of 15', reader.pages[0].extract_text())

    def test_all_unknown_languages_have_no_english_ratio(self):
        self.profile['languages']['document_counts'] = {'unknown': 15}
        self.profile['languages']['unknown_documents'] = 15
        self.profile['languages']['unknown_reasons'] = {'detector_unavailable': 15}
        self.profile['metrics']['english_document_share']['value'] = None
        _, text = self.build()
        self.assertIn('English share: Not available', text)
        self.assertIn('Detector unavailable', text)

    def test_invalid_inputs_preserve_existing_output(self):
        base = copy.deepcopy(self.profile)
        for change in ['schema', 'negative', 'metric', 'language', 'answer', 'text_none', 'text_excess', 'text_denom']:
            with self.subTest(change=change):
                self.profile = copy.deepcopy(base)
                self.answers = {}
                if change == 'schema': self.profile['schema_version'] = '2.0'
                if change == 'negative': self.profile['inventory']['files'] = -1
                if change == 'metric': self.profile['metrics']['selected_files']['value'] = -3
                if change == 'language': self.profile['languages']['denominator'] = 2
                if change == 'answer': self.answers = {'notes': ['not a string']}
                if change == 'text_none': self.profile['metrics']['files_with_extracted_text']['value'] = None
                if change == 'text_excess': self.profile['metrics']['files_with_extracted_text']['value'] = 14
                if change == 'text_denom': self.profile['metrics']['files_with_extracted_text']['denominator'] = 14
                self.out.write_bytes(b'PRIOR OUTPUT')
                with self.assertRaises(ValueError): self.build()
                self.assertEqual(self.out.read_bytes(), b'PRIOR OUTPUT')

    def test_invalid_json_preserves_output(self):
        p, a = self.folder / 'p.json', self.folder / 'a.json'
        p.write_text('{broken')
        a.write_text('{}')
        self.out.write_bytes(b'PRIOR OUTPUT')
        with self.assertRaises(ValueError): render(p, a, self.out)
        self.assertEqual(self.out.read_bytes(), b'PRIOR OUTPUT')

    def test_output_cannot_overwrite_inputs(self):
        p, a = self.folder / 'p.json', self.folder / 'a.json'
        p.write_text(json.dumps(self.profile)); a.write_text('{}')
        before = p.read_bytes()
        with self.assertRaises(ValueError): render(p, a, p)
        self.assertEqual(p.read_bytes(), before)

    def test_output_directory_swap_before_temp_creation_preserves_source_bytes(self):
        source, output = self.folder / 'selected', self.folder / 'report-output'
        source.mkdir(); output.mkdir()
        selected = source / 'original.pdf'
        selected.write_bytes(b'Synthetic source bytes that rendering must never change.')
        before = hashlib.sha256(selected.read_bytes()).hexdigest()
        target = output / 'original.pdf'
        target.write_bytes(b'PRIOR OUTPUT')
        p, a = self.folder / 'p.json', self.folder / 'a.json'
        p.write_text(json.dumps(self.profile)); a.write_text('{}')
        import report
        original_open = report.os.open
        swapped, rejected = False, False

        def swap_before_temp_open(path, *args, **kwargs):
            nonlocal swapped
            if Path(path).name.startswith('.tgdc-card-') and not swapped:
                output.rename(self.folder / 'original-output')
                output.symlink_to(source, target_is_directory=True)
                swapped = True
            return original_open(path, *args, **kwargs)

        with patch('report.os.open', side_effect=swap_before_temp_open) as intercepted:
            # The wrapper delegates to the actual supported descriptor-capable open.
            with patch('report.os.supports_dir_fd', report.os.supports_dir_fd | {intercepted}):
                try:
                    render(p, a, target)
                except (ValueError, OSError):
                    rejected = True
        self.assertTrue(swapped)
        self.assertEqual(hashlib.sha256(selected.read_bytes()).hexdigest(), before)
        self.assertEqual(sorted(path.name for path in source.iterdir()), ['original.pdf'])
        self.assertEqual((self.folder / 'original-output/original.pdf').read_bytes(), b'PRIOR OUTPUT')
        self.assertEqual(sorted(path.name for path in (self.folder / 'original-output').iterdir()), ['original.pdf'])
        self.assertTrue(rejected)

    def test_cli_render_requires_preview_before_voluntary_sharing(self):
        p, a = self.folder / 'p.json', self.folder / 'a.json'
        p.write_text(json.dumps(self.profile)); a.write_text(json.dumps(self.answers))
        result = subprocess.run([sys.executable, str(ROOT / 'scripts/datacard.py'), 'render', '--profile', str(p), '--answers', str(a), '--output', str(self.out)], capture_output=True, text=True)
        self.assertEqual(result.returncode, 0, result.stderr)
        self.assertIn('Review', result.stdout)
        self.assertIn('voluntarily', result.stdout)
        self.assertIn('confidential', result.stdout)

    def test_cli_missing_dependencies_has_clear_safe_message(self):
        result = subprocess.run([sys.executable, '-S', str(ROOT / 'scripts/datacard.py'), 'render', '--profile', 'unread.json', '--answers', 'unread.json', '--output', 'unused.pdf'], capture_output=True, text=True)
        self.assertEqual(result.returncode, 2)
        self.assertIn('pinned Python dependencies', result.stderr)
        self.assertNotIn('Traceback', result.stderr)


if __name__ == '__main__':
    unittest.main()
